/**
 * Emit `tmp/agency-core.mjs`: the delegation-path subset of `src/persona.js`
 * as one self-contained module.
 *
 * Why it exists: a dynamic Cordis Host half is evaluated with only `ctx` and
 * `harness` in scope and cannot `import` this repository, so an in-session
 * end-to-end check cannot simply load `src/persona.js`. Rather than reimplement
 * the logic (which would validate nothing), this script slices the real source
 * from `FIRST_MARKER` onward, so the unit that runs in a session contains the
 * shipped code verbatim. Regenerating it after an edit is one command, and the
 * emitted file is not part of the published surface.
 *
 * The emitted template avoids nested template literals and backticks entirely:
 * `__NL__` stands for a literal `\n` escape inside the emitted source, and the
 * remaining placeholders cover quotes the outer source cannot easily carry.
 *
 * @module dsh-agency-agents/tools/emit-eval-unit
 */

import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const SOURCE = resolve(ROOT, 'src/persona.js')
const TARGET = resolve(ROOT, 'tmp/agency-core.mjs')

/** Everything from this marker to the end of `src/persona.js` is the unit. */
const FIRST_MARKER = '/**\n * Neutralize'

const HEADER = [
  '/**',
  ' * Evaluation unit for in-session validation. Generated by tools/emit-eval-unit.mjs —',
  ' * edit src/persona.js instead.',
  ' *',
  ' * A dynamic Cordis Host half cannot import this repository (it receives only',
  ' * ctx and harness), so the parts of src/persona.js the delegation path depends',
  ' * on are inlined here verbatim: the prompt-template neutralizer and the',
  ' * persona/task composers. The caller supplies the parsed role, having read the',
  ' * real role file from the vendored corpus through the harness fs service.',
  ' */',
  '',
  '',
].join('\n')

const FOOTER = [
  "/** Invisible separator used to break the prompt engine's template token. */",
  "const ZERO_WIDTH_SPACE = '\\u200B'",
  '',
  '/**',
  ' * Minimal frontmatter reader, mirroring src/frontmatter.js.',
  ' *',
  ' * A copy rather than an import for the same reason this whole unit exists: a',
  ' * dynamic Host half has no module loader. It must stay behaviourally identical',
  ' * to the shipped parser.',
  ' */',
  'function parseFrontmatter(text) {',
  "  const normalized = text.replace(/^\\uFEFF/, '').replace(/\\r__NL__/g, '__NL__')",
  "  if (!normalized.startsWith('---')) return { data: {}, body: normalized, hasFrontmatter: false }",
  "  const end = normalized.indexOf('__NL__---', 3)",
  "  if (end < 0) return { data: {}, body: normalized, hasFrontmatter: false }",
  '  const block = normalized.slice(3, end)',
  '  const data = {}',
  '  let currentKey',
  "  for (const rawLine of block.split('__NL__')) {",
  '    const line = rawLine.replace(/\\s+$/, __EMPTY__)',
  "    if (line.trim().length === 0 || line.trimStart().startsWith('#')) continue",
  '    const match = /^([A-Za-z_][A-Za-z0-9_-]*):[ \\t]*(.*)$/.exec(line)',
  '    if (match !== null) {',
  '      currentKey = match[1]',
  '      data[currentKey] = stripQuotes(match[2])',
  '      continue',
  '    }',
  '    if (currentKey !== undefined && /^[ \\t]+\\S/.test(rawLine)) {',
  "      data[currentKey] = (data[currentKey] + ' ' + line.trim()).trim()",
  '    }',
  '  }',
  "  const bodyStart = normalized.indexOf('__NL__', end + 1)",
  "  return { data, body: bodyStart < 0 ? '' : normalized.slice(bodyStart + 1), hasFrontmatter: true }",
  '}',
  '',
  'function stripQuotes(value) {',
  '  const text = value.trim()',
  '  if (text.length >= 2) {',
  '    const first = text[0]',
  '    const last = text[text.length - 1]',
  '    if ((first === __DQ__ && last === __DQ__) || (first === __SQ__ && last === __SQ__)) return text.slice(1, -1)',
  '  }',
  '  return text',
  '}',
  '',
  '/** Read and parse one role file through the harness fs service. */',
  'export async function readRole(fs, path) {',
  '  const target = await fs.resolve(path)',
  '  const text = await fs.readText(target)',
  '  const { data, body } = parseFrontmatter(text)',
  "  if (typeof data.name !== 'string' || data.name.length === 0) {",
  "    throw new Error('not a role definition: ' + path)",
  '  }',
  "  const file = path.slice(path.lastIndexOf('/') + 1).replace(/\\.md$/, '')",
  '  return {',
  '    id: file,',
  '    name: data.name,',
  "    description: typeof data.description === 'string' ? data.description : '',",
  '    path,',
  '    body,',
  '  }',
  '}',
  '',
  '/** Compose the persona a role delegation injects into its child. */',
  'export function personaFor(role, cwd) {',
  '  return buildPersona(role, { cwd })',
  '}',
  '',
  "/** Compose the child's user message. */",
  'export function promptFor(role, task, framing = {}) {',
  '  return buildTaskPrompt(role, task, framing)',
  '}',
  '',
].join('\n')

const source = await readFile(SOURCE, 'utf8')
const start = source.indexOf(FIRST_MARKER)
if (start < 0) throw new Error(`emit-eval: marker not found in ${SOURCE}; update FIRST_MARKER`)
const unit = source.slice(start).trimEnd()
const rendered = `${HEADER}${unit}\n${FOOTER}`
  .split('__NL__')
  .join('\\n')
  .split('__EMPTY__')
  .join("''")
  .split('__DQ__')
  .join('"')
  .split('__SQ__')
  .join("'")
await mkdir(dirname(TARGET), { recursive: true })
await writeFile(TARGET, rendered)
process.stdout.write(`emit-eval: wrote ${TARGET} (${unit.length} chars of shipped source)\n`)
